#!/usr/bin/env python3
"""Fail-closed public contract snapshot and schema-digest guard.

The HTTP snapshot is generated from FastAPI itself.  It is intentionally not
hand-edited: a CI check compares the generated document, the committed
snapshot, the generated TypeScript OpenAPI marker, and every versioned JSON
schema digest.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
import tempfile
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
HTTP_DIR = ROOT / "schemas" / "http" / "v1"
SNAPSHOT_PATH = HTTP_DIR / "openapi.json"
VERSION_PATH = HTTP_DIR / "contract-version.json"
DIGESTS_PATH = ROOT / "schemas" / "schema-digests.v1.json"
TS_GENERATED_PATH = (
    ROOT / "packages" / "typescript" / "controlstudio-contracts" / "src" / "http-openapi.generated.ts"
)
WEB_TYPES_PATH = ROOT / "web" / "src" / "api" / "types.ts"
WEB_TYPES_SINGLE_SOURCE = (
    "/** Public API types are owned and versioned by the Platform contracts package. */\n"
    'export type * from "@controlstudio/contracts";\n'
)


def _canonical_json(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def _digest(value: Any) -> str:
    return hashlib.sha256(_canonical_json(value).encode("utf-8")).hexdigest()


def _read_json(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8"))


def _version() -> dict[str, Any]:
    value = _read_json(VERSION_PATH)
    if not isinstance(value.get("major"), int) or value["major"] < 1:
        raise RuntimeError("schemas/http/v1/contract-version.json must contain a positive integer major")
    return value


def generate_openapi() -> dict[str, Any]:
    """Import the Platform app with isolated ephemeral state."""
    sys.path[:0] = [str(ROOT / "packages" / "python" / "controlstudio-contracts" / "src"), str(ROOT / "host" / "src")]
    from controlstudio_host.app import create_app
    from controlstudio_host.config import HostConfig

    with tempfile.TemporaryDirectory(prefix="controlstudio-openapi-") as directory:
        temporary = Path(directory)
        app = create_app(
            HostConfig(
                database_path=temporary / "host.sqlite3",
                static_dir=temporary / "web-dist",
                launch_token="contract-snapshot-token-that-is-long-enough",
            )
        )
        document = app.openapi()
    document["x-controlstudio-contract-major"] = _version()["major"]
    return document


def _required_properties(schema: dict[str, Any]) -> set[str]:
    required = schema.get("required", [])
    return set(required) if isinstance(required, list) else set()


def breaking_changes(previous: dict[str, Any], current: dict[str, Any]) -> list[str]:
    """Detect removed paths/operations/schemas and newly required fields.

    Type, enum, and constraint compatibility still require review; this
    structural check is not a complete OpenAPI compatibility analysis.
    """
    problems: list[str] = []
    previous_paths = previous.get("paths", {})
    current_paths = current.get("paths", {})
    for path, operations in previous_paths.items():
        if path not in current_paths:
            problems.append(f"removed path {path}")
            continue
        for method in operations:
            if method not in current_paths[path]:
                problems.append(f"removed operation {method.upper()} {path}")
    previous_schemas = previous.get("components", {}).get("schemas", {})
    current_schemas = current.get("components", {}).get("schemas", {})
    for name, schema in previous_schemas.items():
        if name not in current_schemas:
            problems.append(f"removed component schema {name}")
            continue
        old_required = _required_properties(schema)
        new_required = _required_properties(current_schemas[name])
        for field in sorted(new_required - old_required):
            problems.append(f"new required field {name}.{field}")
    return problems


def schema_digests() -> dict[str, str]:
    result: dict[str, str] = {}
    for path in sorted((ROOT / "schemas").glob("**/v1/*.json")):
        if path == VERSION_PATH:
            continue
        result[path.relative_to(ROOT).as_posix()] = _digest(_read_json(path))
    return result


def generated_types(document: dict[str, Any]) -> str:
    operations: list[str] = []
    for path, methods in sorted(document.get("paths", {}).items()):
        for method, operation in sorted(methods.items()):
            if isinstance(operation, dict) and "operationId" in operation:
                operations.append(str(operation["operationId"]))
    digest = _digest(document)
    entries = "\n".join(f'  | "{name}"' for name in operations) or "  | never"
    return f'''/** AUTO-GENERATED by scripts/contracts/contract_guard.py; do not edit. */
/** FastAPI OpenAPI v1 canonical SHA-256: {digest} */
export const HTTP_OPENAPI_V1_SHA256 = "{digest}" as const;

/** Operation IDs generated from the committed FastAPI OpenAPI v1 snapshot. */
export type HttpApiV1OperationId =
{entries};
'''


def write_snapshot(document: dict[str, Any]) -> None:
    previous = _read_json(SNAPSHOT_PATH) if SNAPSHOT_PATH.exists() else None
    if previous is not None:
        old_major = previous.get("x-controlstudio-contract-major", 1)
        new_major = document["x-controlstudio-contract-major"]
        changes = breaking_changes(previous, document)
        if changes and new_major <= old_major:
            raise RuntimeError(
                "breaking HTTP API change requires an incremented api contract major: "
                + "; ".join(changes)
            )
    SNAPSHOT_PATH.write_text(json.dumps(document, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    TS_GENERATED_PATH.write_text(generated_types(document), encoding="utf-8")


def check_snapshot(document: dict[str, Any]) -> list[str]:
    errors: list[str] = []
    if not SNAPSHOT_PATH.exists():
        errors.append("missing schemas/http/v1/openapi.json; run contract_guard.py --write")
    elif _read_json(SNAPSHOT_PATH) != document:
        errors.append("FastAPI OpenAPI v1 snapshot drift; run contract_guard.py --write")
    expected_types = generated_types(document)
    if not TS_GENERATED_PATH.exists() or TS_GENERATED_PATH.read_text(encoding="utf-8") != expected_types:
        errors.append("generated TypeScript OpenAPI operation marker drift; run contract_guard.py --write")
    if not WEB_TYPES_PATH.exists() or WEB_TYPES_PATH.read_text(encoding="utf-8") != WEB_TYPES_SINGLE_SOURCE:
        errors.append("web API types must be the exact single-source contracts re-export")
    return errors


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true", help="regenerate HTTP snapshot and TypeScript marker")
    parser.add_argument("--write-digests", action="store_true", help="regenerate versioned JSON schema digests")
    args = parser.parse_args()
    document = generate_openapi()
    if args.write:
        write_snapshot(document)
    if args.write_digests:
        DIGESTS_PATH.write_text(json.dumps(schema_digests(), indent=2, sort_keys=True) + "\n", encoding="utf-8")
    errors = [] if (args.write or args.write_digests) else check_snapshot(document)
    expected_digests = schema_digests()
    if not DIGESTS_PATH.exists() or _read_json(DIGESTS_PATH) != expected_digests:
        errors.append("versioned schema digest drift; run contract_guard.py --write-digests")
    if errors:
        raise SystemExit("\n".join(errors))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
